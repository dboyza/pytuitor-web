"""Private learner shells: the tutor's Python comes first and global dotfiles stay untouched."""

from __future__ import annotations

import os
import shutil
import sys
from importlib.resources import files
from pathlib import Path

# Variables that describe the server's own terminal rather than the embedded one.
FOREIGN = (
    "TERM_PROGRAM_VERSION", "TERM_SESSION_ID", "TMUX", "TMUX_PANE", "STY", "VTE_VERSION",
    "WT_SESSION", "WT_PROFILE_ID", "COLUMNS", "LINES", "VIRTUAL_ENV", "VIRTUAL_ENV_PROMPT",
    "PYTHONHOME", "PYTHONPATH", "PS1", "PROMPT_COMMAND", "ZDOTDIR",
)  # fmt: skip
FOREIGN_PREFIXES = ("ITERM_", "LC_TERMINAL", "KITTY_", "GHOSTTY_", "WEZTERM_", "ALACRITTY_")
# Nerd Font glyphs render because the embedded terminal bundles JetBrains Mono Nerd Font.
PYTHON_ICON = "\ue73c"
FOLDER_ICON = "\uf07c"

# The welcome banner prints from the rc file, so its text follows each lesson's variables.
WELCOME = (
    "printf '\\n  \\033[1;34m{{PY}}  Pytuitor\\033[0m  \\033[2m·\\033[0m  "
    "\\033[1m%s\\033[0m  \\033[2m·  %s\\033[0m\\n"
    "  \\033[2mThis terminal runs in your %s workspace on this computer.\\033[0m\\n"
    "  \\033[2mType\\033[0m \\033[36m%s\\033[0m "
    "\\033[2mor press Run to try your program.\\033[0m\\n\\n' "
    '"$PYTUITOR_TITLE" "$PYTUITOR_STAGE" "$PYTUITOR_STAGE" "$PYTUITOR_RUN"'
)


def _template(name: str) -> str:
    text = files("pytuitor_web").joinpath("shells", name).read_text(encoding="utf-8")
    text = text.replace("{{WELCOME}}", WELCOME)
    return text.replace("{{PY}}", PYTHON_ICON).replace("{{FOLDER}}", FOLDER_ICON)


def environment(variables: dict[str, str]) -> dict[str, str]:
    env = {
        key: value
        for key, value in os.environ.items()
        if key not in FOREIGN and not key.startswith(FOREIGN_PREFIXES)
    }
    tutor_python = str(Path(sys.executable).parent)
    env["PATH"] = tutor_python + os.pathsep + env.get("PATH", os.defpath)
    env.update(
        TERM="xterm-256color",
        COLORTERM="truecolor",
        TERM_PROGRAM="Pytuitor",
        PYTUITOR_TERMINAL="embedded",
        # Keep generated bytecode out of the learner's workspace.
        PYTHONDONTWRITEBYTECODE="1",
        PYTHONIOENCODING="utf-8",
        **variables,
    )
    if not any(env.get(name) for name in ("LC_ALL", "LC_CTYPE", "LANG")):
        env["LC_CTYPE"] = "UTF-8" if sys.platform == "darwin" else "C.UTF-8"
    return env


def command(rc_directory: Path) -> tuple[list[str], dict[str, str]]:
    """Return the shell argv and the extra variables it needs to load its private rc file."""
    rc_directory.mkdir(parents=True, exist_ok=True)
    if os.name == "nt":
        script = rc_directory / "profile.ps1"
        script.write_text(_template("profile.ps1"), encoding="utf-8-sig")
        executable = shutil.which("pwsh") or shutil.which("powershell") or "powershell.exe"
        return [
            executable,
            "-NoLogo",
            "-NoProfile",
            "-NoExit",
            "-ExecutionPolicy",
            "Bypass",
            "-Command",
            f". '{script}'",
        ], {}
    preferred = Path(os.environ.get("SHELL", "")).name
    order = ["zsh", "bash"] if preferred != "bash" else ["bash", "zsh"]
    for name in order:
        executable = shutil.which(name)
        if not executable:
            continue
        if name == "zsh":
            (rc_directory / ".zshrc").write_text(_template("zshrc"), encoding="utf-8")
            return [executable, "-i"], {"ZDOTDIR": str(rc_directory)}
        rc = rc_directory / ".bashrc"
        rc.write_text(_template("bashrc"), encoding="utf-8")
        return [executable, "--rcfile", str(rc), "-i"], {}
    return ["/bin/sh", "-i"], {"PS1": "$PYTUITOR_LABEL $ "}
